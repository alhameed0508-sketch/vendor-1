"""
Evidence pack PDF for a fraud complaint: the case, its clocks, the finding with the burden-of-proof
checklist, the cited narrative and the hash-chained evidence, ready for the ombudsman or an audit.
"""

from __future__ import annotations

from datetime import datetime
from typing import Dict, Optional

from complaints.rules import format_inr
from fpdf import FPDF

_LINE = 5
_LABEL_WIDTH = 55
_HASH_CHARS = 16


def _text(value) -> str:
    """Core PDF fonts are Latin-1 only, so spell out the rupee sign and drop anything else they lack."""
    return str(value).replace("₹", "INR ").encode("latin-1", "replace").decode("latin-1")


def _money(amount: Optional[int]) -> str:
    return "Set by bank policy" if amount is None else format_inr(amount, "INR ")


def _when(at: Optional[str]) -> str:
    return datetime.fromisoformat(at).strftime("%d %b %Y, %H:%M IST") if at else "-"


class EvidencePack(FPDF):
    def header(self):
        self.set_font("Helvetica", "B", 14)
        self.cell(0, 8, "FRAUD COMPLAINT EVIDENCE PACK", align="C", new_x="LMARGIN", new_y="NEXT")
        self.set_font("Helvetica", "", 9)
        self.cell(0, 5, "RBI directions on fraudulent electronic banking transactions  |  Confidential",
                  align="C", new_x="LMARGIN", new_y="NEXT")
        self.line(10, self.get_y() + 2, 200, self.get_y() + 2)
        self.ln(6)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 7)
        self.cell(0, 10, f"Page {self.page_no()}/{{nb}}  |  Generated by MuleCatch", align="C")

    def section(self, title: str):
        self.ln(2)
        self.set_font("Helvetica", "B", 11)
        self.cell(0, 7, _text(title), new_x="LMARGIN", new_y="NEXT")
        self.set_font("Helvetica", "", 9)

    def row(self, label: str, value):
        self.set_font("Helvetica", "B", 9)
        self.cell(_LABEL_WIDTH, _LINE, _text(label))
        self.set_font("Helvetica", "", 9)
        self.multi_cell(0, _LINE, _text(value), new_x="LMARGIN", new_y="NEXT")

    def para(self, text: str):
        self.multi_cell(0, _LINE, _text(text), new_x="LMARGIN", new_y="NEXT")


def _case(pdf: EvidencePack, pack: Dict):
    pdf.section("1. Complaint")
    for label, value in (
        ("Complaint", pack["complaint_id"]), ("Customer", f"{pack['customer_name']} ({pack['customer_type'].lower()})"),
        ("Account", pack["account"]), ("Channel", pack["channel"]), ("Amount disputed", _money(pack["amount"])),
        ("Fraud occurred", _when(pack["occurred_at"])), ("Reported to bank", _when(pack["reported_at"])),
        ("Beneficiary", f"{pack['beneficiary_account'] or '-'} {pack['beneficiary_bank']}".strip()),
        ("Status", pack["status"]),
    ):
        pdf.row(label, value)

    clocks = pack["deadlines"]
    pdf.section("2. Clocks")
    pdf.row("Resolve by", f"{_when(clocks['resolve_by'])} ({clocks['resolution_limit_days']}-day limit)")
    pdf.row("Reported after", f"{clocks['reported_after_days']} day(s); zero-liability window "
                              f"{'met' if clocks['within_zero_liability_window'] else 'missed'}")
    if clocks["shadow_credit_by"]:
        pdf.row("Shadow credit by", _when(clocks["shadow_credit_by"]))


def _finding(pdf: EvidencePack, pack: Dict):
    finding, liability = pack["finding"], pack["liability"]
    pdf.section("3. Recommendation (the decision is the supervisor's)")
    pdf.row("Category", finding["category"])
    pdf.row("Outcome", liability["outcome"])
    pdf.row("Customer liability", _money(liability["customer_liability"]))
    pdf.row("Basis", liability["basis"])
    for reason in finding["reasons"]:
        pdf.para(f"- {reason['text']} [{', '.join(reason['evidence'])}]")
    if finding["flags"]:
        pdf.row("Flags", ", ".join(finding["flags"]))
    if finding["checklist"]:
        pdf.section("4. Burden of proof")
        for check in finding["checklist"]:
            cited = f" [{', '.join(check['evidence'])}]" if check["evidence"] else ""
            pdf.para(f"{'[MET]    ' if check['met'] else '[MISSING]'} {check['label']}{cited}")

    comp = pack["compensation"]
    pdf.section("5. Small-value fraud compensation")
    for check in comp["checks"]:
        pdf.para(f"{'[MET]    ' if check['met'] else '[NOT MET]'} {check['label']}")
    if comp["eligible"]:
        split = ", ".join(f"{k.replace('_', ' ')} {_money(v)}" for k, v in comp["split"].items())
        pdf.row("Compensation", f"{_money(comp['amount'])} on a net loss of {_money(comp['net_loss'])}")
        pdf.row("Funded by", split)
        pdf.row("Pay by", _when(comp["pay_by"]))


def _evidence(pdf: EvidencePack, pack: Dict):
    pdf.section("6. Narrative")
    for sentence in pack["narrative"]["sentences"]:
        pdf.para(f"{sentence['text']} [{', '.join(sentence['evidence'])}]")
    pdf.section("7. Evidence chain")
    for item in pack["evidence"]:
        pdf.set_font("Helvetica", "B", 9)
        pdf.para(f"{item['id']}  {_when(item['at'])}  {item['source']} / {item['kind']}")
        pdf.set_font("Helvetica", "", 9)
        pdf.para(f"{item['summary']}  (received {_when(item['received_at'])} from {item['submitted_by']}; "
                 f"hash {item['hash'][:_HASH_CHARS]}...)")
    chain = pack["chain"]
    pdf.row("Chain integrity", "Intact" if chain["intact"] else f"Broken at {chain['broken_at']}")


def _decision(pdf: EvidencePack, pack: Dict):
    decision = pack["decision"]
    pdf.section("8. Decision")
    if not decision:
        pdf.para("No decision recorded yet.")
    else:
        pdf.row("Outcome", decision["outcome"])
        pdf.row("Customer liability", _money(decision["customer_liability"]))
        pdf.row("Decided by", f"{decision['decided_by']} on {_when(decision['decided_at'])}")
        followed = decision["followed_recommendation"]
        pdf.row("Followed recommendation", "Bank policy case" if followed is None else ("Yes" if followed else "No"))
        pdf.row("Notes", decision["notes"])
    pdf.ln(2)
    pdf.set_font("Helvetica", "I", 8)
    pdf.para(f"Rules: {pack['rules_source']}. Generated {_when(pack['generated_at'])} by {pack['generated_by']}.")


def build_pack_pdf(pack: Dict) -> bytes:
    pdf = EvidencePack()
    pdf.alias_nb_pages()
    pdf.set_auto_page_break(auto=True, margin=20)
    pdf.add_page()
    for part in (_case, _finding, _evidence, _decision):
        part(pdf, pack)
    return bytes(pdf.output())
