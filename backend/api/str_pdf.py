"""
STR PDF Generator
=================
Generates FIU-IND compliant Suspicious Transaction Report as PDF.
Uses fpdf2 for lightweight server-side PDF creation.
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Dict

from fpdf import FPDF


class STRReport(FPDF):
    """Custom PDF layout for STR filings."""

    def header(self):
        self.set_font("Helvetica", "B", 14)
        self.cell(
            0,
            8,
            "SUSPICIOUS TRANSACTION REPORT (STR)",
            align="C",
            new_x="LMARGIN",
            new_y="NEXT",
        )
        self.set_font("Helvetica", "", 9)
        self.cell(
            0,
            5,
            "FIU-IND Format v2.1  |  Confidential  |  Indian Overseas Bank",
            align="C",
            new_x="LMARGIN",
            new_y="NEXT",
        )
        self.line(10, self.get_y() + 2, 200, self.get_y() + 2)
        self.ln(6)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 7)
        generated = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
        self.cell(
            0,
            10,
            f"Page {self.page_no()}/{{nb}}  |  Generated by MuleCatch  |  {generated}",
            align="C",
        )


def generate_str_pdf(alert: Dict, str_record: Dict) -> bytes:
    """Generate a single-alert STR PDF and return bytes."""
    pdf = STRReport()
    pdf.alias_nb_pages()
    pdf.add_page()
    pdf.set_auto_page_break(auto=True, margin=20)

    # ── Section 1: Alert Summary ─────────────────────────────────────────
    _section_header(pdf, "1. Alert Summary")
    _kv_row(pdf, "STR ID", str_record.get("str_id", "N/A"))
    _kv_row(pdf, "Alert ID", alert.get("alert_id", "N/A"))
    _kv_row(pdf, "Severity", alert.get("severity", "N/A"))
    _kv_row(pdf, "Risk Score", f"{alert.get('risk_score', 0) * 100:.1f}%")
    _kv_row(pdf, "Confidence", f"{alert.get('confidence', 0) * 100:.1f}%")
    if alert.get("gnn_score") is not None:
        _kv_row(pdf, "GNN Score", f"{alert['gnn_score'] * 100:.1f}%")
    _kv_row(pdf, "Total Amount", f"INR {alert.get('total_amount', 0):,.2f}")
    _kv_row(pdf, "Transaction Count", str(alert.get("txn_count", 0)))
    _kv_row(pdf, "Accounts Involved", str(alert.get("account_count", 0)))
    _kv_row(
        pdf,
        "Generated At",
        str_record.get("generated_at", datetime.now(timezone.utc).isoformat()),
    )
    pdf.ln(4)

    # ── Section 2: Reason Codes ──────────────────────────────────────────
    _section_header(pdf, "2. Reason Codes / Indicators")
    for rc in alert.get("reason_codes", []):
        pdf.set_font("Helvetica", "", 9)
        pdf.cell(0, 5, _safe(f"  - {rc}"), new_x="LMARGIN", new_y="NEXT")
    pdf.ln(4)

    # ── Section 3: Accounts Table ────────────────────────────────────────
    _section_header(pdf, "3. Accounts Involved")
    nodes = alert.get("nodes", [])
    if nodes:
        col_w = [35, 25, 30, 25, 25, 20, 30]
        headers = ["Account ID", "Role", "Bank", "City", "Smurf %", "Age(d)", "KYC"]
        pdf.set_font("Helvetica", "B", 8)
        for i, h in enumerate(headers):
            pdf.cell(col_w[i], 6, h, border=1)
        pdf.ln()
        pdf.set_font("Helvetica", "", 7)
        for n in nodes:
            vals = [
                n.get("account_id", "")[:14],
                n.get("role", ""),
                n.get("bank", ""),
                n.get("city", ""),
                f"{n.get('smurf_score', 0) * 100:.0f}%",
                str(n.get("account_age_days", "")),
                n.get("kyc_status", ""),
            ]
            for i, v in enumerate(vals):
                pdf.cell(col_w[i], 5, v, border=1)
            pdf.ln()
    pdf.ln(4)

    # ── Section 4: Transaction Edges ─────────────────────────────────────
    _section_header(pdf, "4. Transaction Flows")
    edges = alert.get("edges", [])
    if edges:
        col_w = [35, 35, 30, 20, 30]
        headers = ["From", "To", "Amount (INR)", "Count", "Pattern"]
        pdf.set_font("Helvetica", "B", 8)
        for i, h in enumerate(headers):
            pdf.cell(col_w[i], 6, h, border=1)
        pdf.ln()
        pdf.set_font("Helvetica", "", 7)
        for e in edges:
            vals = [
                e.get("from_account", "")[:14],
                e.get("to_account", "")[:14],
                f"{e.get('total_amount', 0):,.0f}",
                str(e.get("txn_count", 0)),
                e.get("pattern", ""),
            ]
            for i, v in enumerate(vals):
                pdf.cell(col_w[i], 5, v, border=1)
            pdf.ln()
    pdf.ln(4)

    # ── Section 5: Shared Fingerprints ───────────────────────────────────
    shared_devs = alert.get("shared_devices", [])
    shared_ips = alert.get("shared_ips", [])
    if shared_devs or shared_ips:
        _section_header(pdf, "5. Shared Fingerprints")
        for d in shared_devs:
            _kv_row(pdf, "Device", d)
        for ip in shared_ips:
            _kv_row(pdf, "IP Address", ip)
        pdf.ln(4)

    # ── Section 6: Narrative (if available) ──────────────────────────────
    narrative = alert.get("narrative", {})
    if narrative:
        _section_header(pdf, "6. Investigation Narrative")
        if narrative.get("executive_summary"):
            pdf.set_font("Helvetica", "B", 9)
            pdf.cell(0, 5, "Executive Summary", new_x="LMARGIN", new_y="NEXT")
            pdf.set_font("Helvetica", "", 8)
            pdf.cell(
                0,
                4,
                _safe(narrative["executive_summary"]),
                new_x="LMARGIN",
                new_y="NEXT",
            )
            pdf.ln(2)
        if narrative.get("regulatory_summary"):
            pdf.set_font("Helvetica", "B", 9)
            pdf.cell(0, 5, "Regulatory Summary", new_x="LMARGIN", new_y="NEXT")
            pdf.set_font("Helvetica", "", 8)
            pdf.cell(
                0,
                4,
                _safe(narrative["regulatory_summary"]),
                new_x="LMARGIN",
                new_y="NEXT",
            )
            pdf.ln(2)

    # ── Section 7: Mule Classification ───────────────────────────────────
    classification = alert.get("mule_classification", {})
    if classification:
        _section_header(pdf, "7. Mule Classification")
        _kv_row(pdf, "Type", classification.get("mule_type", "N/A"))
        _kv_row(pdf, "Confidence", f"{classification.get('type_confidence', 0) * 100:.0f}%")
        _kv_row(pdf, "Sophistication", classification.get("sophistication_level", "N/A"))
        pdf.ln(4)

    # ── Compliance footer ────────────────────────────────────────────────
    pdf.ln(6)
    pdf.set_font("Helvetica", "I", 8)
    disclaimer = (
        "This report has been auto-generated by the MuleCatch Detection System in compliance "
        "with RBI Master Direction on KYC (Updated 2023) and PMLA Rules. "
        "The reporting entity shall file this STR with FIU-IND within 7 days "
        "of raising suspicion as per Section 12(1) of PMLA, 2002."
    )
    # Split long text to avoid fpdf horizontal space issues
    for line in [disclaimer[i : i + 95] for i in range(0, len(disclaimer), 95)]:
        pdf.cell(0, 4, line.strip(), new_x="LMARGIN", new_y="NEXT")

    return bytes(pdf.output())


def _section_header(pdf: FPDF, title: str):
    pdf.set_font("Helvetica", "B", 11)
    pdf.set_fill_color(20, 30, 50)
    pdf.set_text_color(220, 230, 255)
    pdf.cell(0, 7, f"  {title}", fill=True, new_x="LMARGIN", new_y="NEXT")
    pdf.set_text_color(0, 0, 0)
    pdf.ln(3)


def _safe(text: str) -> str:
    """Replace non-Latin1 characters for fpdf Helvetica compatibility."""
    return text.replace("\u20b9", "INR ").encode("latin-1", errors="replace").decode("latin-1")


def _kv_row(pdf: FPDF, key: str, value: str):
    pdf.set_font("Helvetica", "B", 9)
    pdf.cell(45, 5, _safe(key))
    pdf.set_font("Helvetica", "", 9)
    pdf.cell(0, 5, _safe(value), new_x="LMARGIN", new_y="NEXT")
